# Install the real NevanCode workspace and expose it as `nevan` on Windows.
# This does NOT wrap the published `codebuff` npm package. It downloads this
# repository, installs Bun dependencies, prepares a local dev/proxy server, and
# creates a launcher that starts Nevan services before opening the Nevan CLI.

$ErrorActionPreference = 'Stop'

$RepoOwner = if ($env:NEVAN_REPO_OWNER) { $env:NEVAN_REPO_OWNER } else { 'nevanai' }
$RepoName = if ($env:NEVAN_REPO_NAME) { $env:NEVAN_REPO_NAME } else { 'NevanCode' }
$RepoBranch = if ($env:NEVAN_REPO_BRANCH) { $env:NEVAN_REPO_BRANCH } else { 'main' }
$NevanHome = if ($env:NEVAN_HOME) { $env:NEVAN_HOME } else { Join-Path $env:USERPROFILE '.nevan' }
$RepoDir = if ($env:NEVAN_REPO_DIR) { $env:NEVAN_REPO_DIR } else { Join-Path $NevanHome $RepoName }
$InstallDir = if ($env:NEVAN_INSTALL_DIR) { $env:NEVAN_INSTALL_DIR } else { Join-Path $env:LOCALAPPDATA 'Nevan\bin' }
$WebPort = if ($env:NEVAN_WEB_PORT) { $env:NEVAN_WEB_PORT } else { '3000' }
$AppUrl = if ($env:NEVAN_APP_URL) { $env:NEVAN_APP_URL } else { "http://localhost:$WebPort" }
$ZipUrl = "https://github.com/$RepoOwner/$RepoName/archive/refs/heads/$RepoBranch.zip"

function Info($Message) { Write-Host "==> $Message" -ForegroundColor Cyan }
function Ok($Message) { Write-Host "✓ $Message" -ForegroundColor Green }
function Warn($Message) { Write-Host "! $Message" -ForegroundColor Yellow }

function Ensure-Bun {
  $bun = Get-Command bun -ErrorAction SilentlyContinue
  if ($bun) { return $bun.Source }

  if ($env:NEVAN_INSTALL_TEST_MODE -eq '1') { return 'bun' }

  Info 'Bun was not found; installing Bun automatically'
  irm https://bun.sh/install.ps1 | iex

  $candidate = Join-Path $env:USERPROFILE '.bun\bin\bun.exe'
  if (Test-Path $candidate) { return $candidate }

  $bun = Get-Command bun -ErrorAction SilentlyContinue
  if ($bun) { return $bun.Source }

  throw 'Bun installation finished, but bun was not found. Reopen PowerShell and run the installer again.'
}

function Install-Repo {
  if ($env:NEVAN_INSTALL_TEST_MODE -eq '1') {
    New-Item -ItemType Directory -Force -Path (Join-Path $RepoDir 'cli\src') | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $RepoDir 'debug\console') | Out-Null
    $packageJson = Join-Path $RepoDir 'package.json'
    if (-not (Test-Path $packageJson)) {
      '{"scripts":{"up":"echo up","down":"echo down","ps":"echo ps"}}' | Set-Content -Path $packageJson -Encoding UTF8
    }
    return
  }

  New-Item -ItemType Directory -Force -Path $NevanHome | Out-Null
  $temp = Join-Path ([System.IO.Path]::GetTempPath()) ("nevancode-" + [System.Guid]::NewGuid().ToString('N'))
  New-Item -ItemType Directory -Force -Path $temp | Out-Null
  try {
    $zipPath = Join-Path $temp 'nevancode.zip'
    Info "Downloading NevanCode from $RepoOwner/$RepoName ($RepoBranch)"
    Invoke-WebRequest -Uri $ZipUrl -OutFile $zipPath
    Expand-Archive -Path $zipPath -DestinationPath $temp -Force
    $extracted = Get-ChildItem -Path $temp -Directory | Where-Object { $_.Name -like "$RepoName-*" } | Select-Object -First 1
    if (-not $extracted) { throw 'Could not find extracted NevanCode directory.' }

    if (Test-Path $RepoDir) { Remove-Item -Path $RepoDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $RepoDir | Out-Null
    Copy-Item -Path (Join-Path $extracted.FullName '*') -Destination $RepoDir -Recurse -Force
  } finally {
    Remove-Item -Path $temp -Recurse -Force -ErrorAction SilentlyContinue
  }
}

