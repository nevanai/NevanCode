function Install-Dependencies($BunPath) {
  if ($env:NEVAN_INSTALL_TEST_MODE -eq '1') {
    Ok 'Test mode: skipped dependency installation'
    return
  }

  Info 'Installing NevanCode dependencies with Bun'
  & $BunPath install --cwd $RepoDir
}

function Test-RequiredDependencies {
  $required = @(
    (Join-Path $RepoDir 'node_modules\react\jsx-dev-runtime.js'),
    (Join-Path $RepoDir 'node_modules\next\package.json'),
    (Join-Path $RepoDir 'node_modules\drizzle-kit\package.json')
  )

  foreach ($path in $required) {
    if (-not (Test-Path $path)) { return $false }
  }
  return $true
}

function Write-Launcher($BunPath) {
  New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null

  $psLauncher = Join-Path $InstallDir 'nevan.ps1'
  @"
`$ErrorActionPreference = 'Stop'

`$RepoOwner = '$RepoOwner'
`$RepoName = '$RepoName'
`$RepoBranch = '$RepoBranch'
`$RepoDir = if (`$env:NEVAN_REPO_DIR) { `$env:NEVAN_REPO_DIR } else { '$RepoDir' }
`$BunPath = if (`$env:BUN_BIN) { `$env:BUN_BIN } else { '$BunPath' }
`$WebPort = if (`$env:NEVAN_WEB_PORT) { `$env:NEVAN_WEB_PORT } else { '$WebPort' }
`$AppUrl = if (`$env:NEVAN_APP_URL) { `$env:NEVAN_APP_URL } else { "http://localhost:`$WebPort" }
`$UserCwd = (Get-Location).Path

function Usage {
  Write-Host 'Nevan CLI'
  Write-Host ''
  Write-Host 'Usage:'
  Write-Host '  nevan [prompt/options]       Start Nevan. Services/proxy start automatically.'
  Write-Host '  nevan --setup-only           Start only the background server/proxy stack.'
  Write-Host '  nevan --status               Show Nevan background service status.'
  Write-Host '  nevan --stop                 Stop Nevan background services.'
  Write-Host '  nevan --update               Re-run the installer/update NevanCode.'
}

if (-not (Test-Path `$RepoDir)) {
  Write-Error "NevanCode workspace is missing at: `$RepoDir. Reinstall with: irm https://raw.githubusercontent.com/$RepoOwner/$RepoName/$RepoBranch/scripts/install-nevan.ps1 | iex"
  exit 1
}

if (-not (Test-Path `$BunPath)) {
  `$bun = Get-Command bun -ErrorAction SilentlyContinue
  if (`$bun) { `$BunPath = `$bun.Source } else { throw 'Bun is required. Install it from https://bun.sh/ and run nevan again.' }
}

function Test-Health {
  try {
    `$response = Invoke-WebRequest -Uri "`$AppUrl/api/healthz" -UseBasicParsing -TimeoutSec 3
    return (`$response.StatusCode -ge 200 -and `$response.StatusCode -lt 300)
  } catch { return `$false }
}

function Load-NevanEnv {
  `$envFile = Join-Path `$RepoDir '.env.local'
  if (-not (Test-Path `$envFile)) { `$envFile = Join-Path `$RepoDir '.env' }
  if (Test-Path `$envFile) {
    Get-Content `$envFile | ForEach-Object {
      if (`$_ -and -not `$_.StartsWith('#') -and `$_.Contains('=')) {
        `$parts = `$_.Split('=', 2)
        [Environment]::SetEnvironmentVariable(`$parts[0], `$parts[1], 'Process')
      }
    }
  }
  `$script:AppUrl = if (`$env:NEXT_PUBLIC_CODEBUFF_APP_URL) { `$env:NEXT_PUBLIC_CODEBUFF_APP_URL } else { `$AppUrl }
  `$script:WebPort = if (`$env:NEXT_PUBLIC_WEB_PORT) { `$env:NEXT_PUBLIC_WEB_PORT } else { `$WebPort }
}

function Ensure-NevanDependencies {
  `$required = @(
    (Join-Path `$RepoDir 'node_modules\react\jsx-dev-runtime.js'),
    (Join-Path `$RepoDir 'node_modules\next\package.json'),
    (Join-Path `$RepoDir 'node_modules\drizzle-kit\package.json')
  )

  `$missing = `$false
  foreach (`$path in `$required) {
    if (-not (Test-Path `$path)) { `$missing = `$true; break }
  }

  if (`$missing) {
    Write-Host 'Nevan dependencies are missing or incomplete; repairing with Bun...'
    & `$BunPath install --cwd `$RepoDir --force
    if (`$LASTEXITCODE -ne 0) { exit `$LASTEXITCODE }
  }
}

function Start-NevanServices {
  Load-NevanEnv
  Ensure-NevanDependencies
  if (Test-Health) { return }
  Write-Host "Starting Nevan server/proxy stack in the background on `$AppUrl ..."
  Write-Host "Ports: web/proxy=`$WebPort, postgres=5432, studio=4983"
  `$env:NEXT_PUBLIC_CODEBUFF_APP_URL = `$AppUrl
  `$env:NEXT_PUBLIC_WEB_PORT = `$WebPort
  `$env:PORT = `$WebPort
  & `$BunPath --cwd `$RepoDir up
  if (`$LASTEXITCODE -ne 0) { exit `$LASTEXITCODE }
}

switch (`$args[0]) {
  '--help' { Usage; exit 0 }
  '-h' { Usage; exit 0 }
  '--setup-only' { Start-NevanServices; Write-Host "Nevan server/proxy is ready at `$AppUrl"; exit 0 }
  '--status' { & `$BunPath --cwd `$RepoDir ps; exit `$LASTEXITCODE }
  '--stop' { & `$BunPath --cwd `$RepoDir down; exit `$LASTEXITCODE }
  '--update' { irm "https://raw.githubusercontent.com/$RepoOwner/$RepoName/$RepoBranch/scripts/install-nevan.ps1" | iex; exit `$LASTEXITCODE }
}

Start-NevanServices
Set-Location (Join-Path `$RepoDir 'cli')
Ensure-NevanDependencies
try { & `$BunPath run scripts/prebuild-agents.ts *> `$null } catch {}
& `$BunPath run src/index.tsx --cwd `$UserCwd @args
exit `$LASTEXITCODE
"@ | Set-Content -Path $psLauncher -Encoding UTF8

  $cmdLauncher = Join-Path $InstallDir 'nevan.cmd'
  @"
@echo off
powershell -NoProfile -ExecutionPolicy Bypass -File "$psLauncher" %*
"@ | Set-Content -Path $cmdLauncher -Encoding ASCII
}

Info 'Installing Nevan CLI (not Codebuff wrapper)'
$BunPath = Ensure-Bun
Install-Repo
Write-DefaultEnv
Install-Dependencies -BunPath $BunPath
if ($env:NEVAN_INSTALL_TEST_MODE -ne '1') {
  if (-not (Test-RequiredDependencies)) {
    Warn 'Dependency install appears incomplete; retrying once with --force'
    & $BunPath install --cwd $RepoDir --force
  }
  if (-not (Test-RequiredDependencies)) {
    throw 'NevanCode dependency installation is incomplete. Missing react/jsx-dev-runtime.js, next, or drizzle-kit.'
  }
}
Write-Launcher -BunPath $BunPath

$userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
$pathParts = @()
if ($userPath) { $pathParts = $userPath -split ';' }
if ($pathParts -notcontains $InstallDir) {
  $newUserPath = if ($userPath) { "$userPath;$InstallDir" } else { $InstallDir }
  [Environment]::SetEnvironmentVariable('Path', $newUserPath, 'User')
  $env:Path = "$env:Path;$InstallDir"
  Ok "Added to user PATH: $InstallDir"
}

Ok "Nevan command installed at $InstallDir\nevan.cmd"

if ($env:NEVAN_SKIP_AUTO_START -eq '1' -or $env:NEVAN_INSTALL_TEST_MODE -eq '1') {
  Write-Host 'Run: nevan'
} else {
  Info 'Preparing Nevan background server/proxy now'
  try { & (Join-Path $InstallDir 'nevan.cmd') --setup-only } catch { Warn "Auto-start did not finish. Run 'nevan --status' or check $RepoDir\debug\console\*.log." }
  Write-Host 'Run: nevan'
}
