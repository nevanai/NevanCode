  function Ensure-EnvVar($Key, $Value) {
    if (-not (Select-String -Path $envFile -Pattern "^$([regex]::Escape($Key))=" -Quiet)) {
      Add-Content -Path $envFile -Value "$Key=$Value"
    }
  }

  Ensure-EnvVar 'NEXT_PUBLIC_CB_ENVIRONMENT' 'dev'
  Ensure-EnvVar 'NEXT_PUBLIC_CODEBUFF_APP_URL' $AppUrl
  Ensure-EnvVar 'NEXT_PUBLIC_WEB_PORT' $WebPort
